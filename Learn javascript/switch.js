//1
const day = "Monday";

switch (day) {
  case "Monday":
    console.log("Thứ hai");
    break;
  case "Tuesday":
    console.log("Thứ ba");
    break;
  case "Wednesday":
    console.log("Thứ tư");
    break;
  default:
    console.log("Ngày khác");
}

